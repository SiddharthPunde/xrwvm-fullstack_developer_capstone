const express=require('express');
const mongoose=require('mongoose');
const fs=require('fs');
const path=require('path');
const cors=require('cors');
const app=express(), port=3030;
app.use(cors());
app.use(express.json());
const reviewsData=JSON.parse(fs.readFileSync(path.join(__dirname,'data','reviews.json'),'utf8'));
const dealersData=JSON.parse(fs.readFileSync(path.join(__dirname,'data','dealerships.json'),'utf8'));
mongoose.connect(process.env.MONGO_URL||'mongodb://mongo_db:27017/',{dbName:'dealershipsDB'})
 .then(async()=>{const Reviews=require('./review'),Dealerships=require('./dealership');
 await Reviews.deleteMany({}); await Reviews.insertMany(reviewsData.reviews);
 await Dealerships.deleteMany({}); await Dealerships.insertMany(dealersData.dealerships);
 console.log('MongoDB seeded');}).catch(err=>console.error('MongoDB connection error:',err));
const Reviews=require('./review'),Dealerships=require('./dealership');
app.get('/',(req,res)=>res.send('Welcome to the Mongoose API'));
app.get('/fetchReviews',async(req,res)=>{try{res.json(await Reviews.find())}catch(e){res.status(500).json({error:'Error fetching reviews'})}});
app.get('/fetchReviews/dealer/:id',async(req,res)=>{try{res.json(await Reviews.find({dealership:Number(req.params.id)}))}catch(e){res.status(500).json({error:'Error fetching reviews'})}});
app.get('/fetchDealers',async(req,res)=>{try{res.json(await Dealerships.find())}catch(e){res.status(500).json({error:'Error fetching dealerships'})}});
app.get('/fetchDealers/:state',async(req,res)=>{try{res.json(await Dealerships.find({state:new RegExp('^'+req.params.state+'$','i')}))}catch(e){res.status(500).json({error:'Error filtering dealerships'})}});
app.get('/fetchDealer/:id',async(req,res)=>{try{const dealer=await Dealerships.findOne({id:Number(req.params.id)});if(!dealer)return res.status(404).json({error:'Dealer not found'});res.json(dealer)}catch(e){res.status(500).json({error:'Error fetching dealer'})}});
app.post('/insert_review',async(req,res)=>{try{const last=await Reviews.findOne().sort({id:-1});const saved=await Reviews.create({...req.body,id:last?last.id+1:1});res.status(201).json(saved)}catch(e){res.status(500).json({error:'Error inserting review'})}});
app.listen(port,()=>console.log('Server is running on http://localhost:'+port));
